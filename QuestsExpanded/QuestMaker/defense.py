def section():
    out = [SECTION_START, "\t<insertAfter xpath=\"/quests/quest[@id='tier2_buried_supplies']\">"]
    ids = []
    for tier in CLEAR_AND_DEFEND_TIERS:
        qid, lines = clear_and_defend(tier)
        ids.append(qid)
        out += ["\t\t" + line if line else "" for line in lines]
        out.append("")
    out[-1] = "\t</insertAfter>"
    out += ["", "\t<append xpath=\"/quests/quest_list[starts-with(@id, 'trader_')]\">"]
    out += [f'\t\t<quest id="{qid}"/>' for qid in ids]
    out += ["\t</append>", SECTION_END]
    return "\n".join(out)


def csv_field(text):
    return '"' + text.replace('"', '""') + '"' if any(c in text for c in ',"') else text


def localization_rows():
    rows = [f"{key},UI,Quest,,,,{csv_field(text)},,,,,,,,,,,,," for key, text in WAVE_TEXT.items()]
    for key, text in CLEAR_AND_DEFEND_TEXT.items():
        kind = ("Quest", "Quest Info") if key.endswith(("_statement", "_response")) else ("quests", "Quests")
        rows.append(f"{key},{kind[0]},{kind[1]},,,,{csv_field(text)},,,,,,,,,,,,,")
    for tier in CLEAR_AND_DEFEND_TIERS:
        rows.append(f"defense_t{tier}_clear_and_defend_name,quests,Quests,,,,Tier {tier} Clear and Defend,,,,,,,,,,,,,")
    return rows


def update_mod(mod_dir):
    quests_path = os.path.join(mod_dir, "Config", "quests.xml")
    quests = open(quests_path, encoding="utf-8", newline="").read().replace("\r\n", "\n")
    block = section()
    if SECTION_START in quests:
        quests = re.sub(re.escape(SECTION_START) + ".*?" + re.escape(SECTION_END), lambda m: block, quests, flags=re.S)
    else:
        end = quests.rindex("</Dementive>")
        quests = quests[:end].rstrip("\n") + "\n\n" + block + "\n\n" + quests[end:]
    open(quests_path, "w", encoding="utf-8", newline="").write(quests.replace("\n", "\r\n"))

    loc_path = os.path.join(mod_dir, "Config", "Localization.csv")
    loc = open(loc_path, encoding="utf-8", newline="").read().replace("\r\n", "\n").rstrip("\n").split("\n")
    loc = [line for line in loc if not line.startswith(("defense_", "DefendWavesDEM_"))] + localization_rows()
    open(loc_path, "w", encoding="utf-8", newline="").write("\r\n".join(loc) + "\r\n")


if __name__ == "__main__":
    for mod in MODS:
        update_mod(mod)
    print(f"{len(CLEAR_AND_DEFEND_TIERS)} defense quests written to {len(MODS)} mods")
