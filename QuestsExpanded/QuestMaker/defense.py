"""Defense quests: quests built on the DefendWavesDEM objective (waves run by WaveDirectorDEM in QuestsExpanded.dll).

Run from anywhere: python defense.py
Rewrites the defense section of Config/quests.xml and the defense rows of Config/Localization.csv in
QuestsExpanded and ZZZTongPrefabs-QuestsExpanded, like commissions.py does for commissions.

For now this is the Clear and Defend prototype (tier 2 only), to playtest the wave system before the other
defense types in PlannedQuests.md are built on it.
"""
import os
import re

from rewards import Rewards

HERE = os.path.dirname(os.path.abspath(__file__))
MODS = [os.path.join(HERE, ".."), os.path.join(HERE, "..", "..", "ZZZTongPrefabs-QuestsExpanded")]

SECTION_START = "\t<!-- Defense quests: generated by QuestMaker/defense.py, don't edit by hand -->"
SECTION_END = "\t<!-- End of defense quests -->"

# Waves by tier (PlannedQuests.md: 3 at tiers 1-2, 4 at tiers 3-4, 5 at tiers 5-6)
WAVES = {1: 3, 2: 3, 3: 4, 4: 4, 5: 5, 6: 5}

CLEAR_AND_DEFEND_TIERS = [2]

