def reward_set(base, tier):
    return [line.strip() for line in getattr(Rewards(), f"tier{tier}_{base}_rewards").strip("\n").split("\n")]


def last_stand_rewards(tier):
    lines = reward_set("clear", tier)
    exp = int(re.search(r'type="Exp" value="(\d+)"', "\n".join(lines)).group(1))
    dukes = int(re.search(r'id="casinoCoin" value="(\d+)"', "\n".join(lines)).group(1))
    per_wave = [int(round(v / LAST_STAND_PAY_SPREAD / 5.0)) * 5 for v in (exp, dukes)]
    # The waves pay the experience and dukes; the loot picks are the tier's usual ones (every vanilla quest has some)
    picks = [line for line in lines if line and 'type="Exp"' not in line and 'id="casinoCoin"' not in line]
    return [f'\t<reward type="LastStandDEM, QuestsExpanded" value="{per_wave[0]},{per_wave[1]}"/>', ""] + ["\t" + line for line in picks]


def rewards(kind, tier, infested):
    if kind == "last_stand":
        return last_stand_rewards(tier)
    base, factor = REWARDS[kind]
    if infested:
        factor *= INFESTED_REWARD_FACTOR
    if base == "compound":
        if tier == 1:
            base, factor = "clear", factor * 1.15
        else:
            base = "fetch_and_clear"
    lines = reward_set(base, tier)

    def scale(match):
        return f'{match.group(1)}{int(round(int(match.group(2)) * factor / 50.0)) * 50}"'

    lines = [re.sub(r'(<reward type="(?:Exp|Item" id="casinoCoin)" value=")(\d+)"', scale, line) for line in lines]
    while not lines[-1]:
        lines.pop()
    return [("\t" + line) if line else "" for line in lines]


