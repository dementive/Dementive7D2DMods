def objective(kind, phase, **props):
    lines = [f'<objective type="{kind}">', f'\t<property name="phase" value="{phase}"/>']
    lines += [f'\t<property name="{name}" value="{value}"/>' for name, value in props.items()]
    return lines + ["</objective>"]


def poi_tier(tier, infested):
    """POI tier for the quest: vanilla infested quests use POIs a tier lower, and there are no tier 6 POIs."""
    return min(tier - 1 if infested else tier, 5)


def go_to_poi(tier, infested):
    return objective("RandomPOIGoto", 1, biome_filter_type="SameBiome", biome_filter="", nav_object="quest",
                     poi_tier=poi_tier(tier, infested)) + \
        objective("RallyPoint", 2, nav_object="rally",
                  rally_marker_type="questRallyMarkerInfestation" if infested else "questRallyMarkerClear")


