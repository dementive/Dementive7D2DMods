def section(quests):
    out = [SECTION_START, "\t<insertAfter xpath=\"/quests/quest[@id='tier2_buried_supplies']\">"]
    for _, _, lines in quests:
        out += ["\t\t" + line if line else "" for line in lines]
        out.append("")
    out[-1] = "\t</insertAfter>"
    out += ["", "\t<append xpath=\"/quests/quest_list[starts-with(@id, 'trader_')]\">"]
    out += [f'\t\t<quest id="{qid}"/>' for qid, _, _ in quests]
    out += ["\t</append>", SECTION_END]
    return "\n".join(out)


def gameevents():
    out = [
        "<Dementive>",
        "",
        "\t<!-- Generated by QuestMaker/defense.py, don't edit by hand -->",
        "\t<!-- Supply kits the build quests give when they are accepted (a quest GameEvent action in phase 1) -->",
        '\t<append xpath="/gameevents">',
    ]
    for name, flag, tiers in KIT_EVENTS:
        for tier in tiers:
            items = ([(flag, 1)] if flag else []) + KITS[tier]
            out += [
                f'\t\t<action_sequence name="{name}{tier}">',
                '\t\t\t<property name="allow_user_trigger" value="false"/>',
                '\t\t\t<action class="AddItems">',
                f'\t\t\t\t<property name="added_items" value="{",".join(item for item, _ in items)}"/>',
                f'\t\t\t\t<property name="added_item_counts" value="{",".join(str(count) for _, count in items)}"/>',
                "\t\t\t</action>",
                "\t\t</action_sequence>",
            ]
    out += ["\t</append>", "", "</Dementive>", ""]
    return "\n".join(out)


def csv_field(text):
    return '"' + text.replace('"', '""') + '"' if any(c in text for c in ',"') else text


def localization_rows(quests):
    rows = [f"{key},UI,Quest,,,,{csv_field(text)},,,,,,,,,,,,," for key, text in OBJECTIVE_TEXT.items()]
    for text_kind, texts in QUEST_TEXT.items():
        for field, text in texts.items():
            if field == "title":
                continue
            kind = ("Quest", "Quest Info") if field in ("statement", "response") else ("quests", "Quests")
            rows.append(f"defense_{text_kind}_{field},{kind[0]},{kind[1]},,,,{csv_field(text)},,,,,,,,,,,,,")
    for qid, title, _ in quests:
        rows.append(f"{qid}_name,quests,Quests,,,,{csv_field(title)},,,,,,,,,,,,,")
    return rows


def update_mod(mod_dir, quests):
    quests_path = os.path.join(mod_dir, "Config", "quests.xml")
    text = open(quests_path, encoding="utf-8", newline="").read().replace("\r\n", "\n")
    block = section(quests)
    if SECTION_START in text:
        text = re.sub(re.escape(SECTION_START) + ".*?" + re.escape(SECTION_END), lambda m: block, text, flags=re.S)
    else:
        end = text.rindex("</Dementive>")
        text = text[:end].rstrip("\n") + "\n\n" + block + "\n\n" + text[end:]
    open(quests_path, "w", encoding="utf-8", newline="").write(text.replace("\n", "\r\n"))

    events_path = os.path.join(mod_dir, "Config", "gameevents.xml")
    open(events_path, "w", encoding="utf-8", newline="").write(gameevents().replace("\n", "\r\n"))

    loc_path = os.path.join(mod_dir, "Config", "Localization.csv")
    loc = open(loc_path, encoding="utf-8", newline="").read().replace("\r\n", "\n").rstrip("\n").split("\n")
    loc = [line for line in loc if not line.startswith(LOC_PREFIXES)] + localization_rows(quests)
    open(loc_path, "w", encoding="utf-8", newline="").write("\r\n".join(loc) + "\r\n")


