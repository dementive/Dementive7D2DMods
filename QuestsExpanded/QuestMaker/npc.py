def scaled_rewards(kind, tier):
    """The tier's reward set with experience and dukes times the quest kind's factor."""
    base, factor = REWARDS[kind]
    lines = reward_set(base, tier)

    def scale(match):
        return f'{match.group(1)}{int(round(int(match.group(2)) * factor / 50.0)) * 50}"'

    lines = [re.sub(r'(<reward type="(?:Exp|Item" id="casinoCoin)" value=")(\d+)"', scale, line) for line in lines]
    while not lines[-1]:
        lines.pop()
    return lines


def rescue_rewards(tier):
    """Experience and dukes that grow with the survivors saved, the tier's loot picks, and from tier 4 a survivor
    joining you as one of the picks."""
    lines = scaled_rewards("rescue", tier)
    text = "\n".join(lines)
    exp = int(re.search(r'type="Exp" value="(\d+)"', text).group(1))
    dukes = int(re.search(r'id="casinoCoin" value="(\d+)"', text).group(1))
    picks = [line for line in lines if line and 'type="Exp"' not in line and 'id="casinoCoin"' not in line]
    out = [f'<reward type="RescueDEM, QuestsExpanded" value="{exp},{dukes}"/>', ""] + picks
    if tier >= RESCUE_JOIN_FROM_TIER:
        join_dukes = int(round(dukes * RESCUE_JOIN_DUKES_SHARE / 50.0)) * 50
        out.append(f'<reward type="RescueJoinDEM, QuestsExpanded" ischosen="true" value="{join_dukes}"/>')
    return out


def quest(qid, kind, tier, body, rewards, poi):
    lines = [
        f'<quest id="{qid}">',
        f'\t<property name="name_key" value="{qid}_name"/>',
    ]
    for field in ("subtitle", "description", "offer", "statement", "response", "completion"):
        lines.append(f'\t<property name="{field}_key" value="npcquest_{kind}_{field}"/>')
    lines += [
        f'\t<property name="icon" value="{ICONS[kind]}"/>',
        '\t<property name="category_key" value="quest"/>',
        f'\t<property name="difficulty_tier" value="{tier}"/>',
        '\t<property name="repeatable" value="true"/>',
        '\t<property name="shareable" value="true"/>',
        '\t<property name="reward_choices_count" value="5"/>',
        '\t<property name="completiontype" value="TurnIn"/>',
    ]
    if poi:
        lines += ['\t<property name="login_rally_reset" value="true"/>', '\t<property name="filter_tags" value="poi"/>']
    lines.append("")
    lines += ["\t" + line for line in body]
    lines.append("")
    lines += [("\t" + line) if line else "" for line in rewards]
    lines.append("</quest>")
    return lines


def bandit_hideout(tier):
    extra = {"leader": "true"} if tier >= HIDEOUT_LEADER_FROM_TIER else {}
    body = go_to_poi(tier, False) + \
        objective("BanditHideoutDEM, QuestsExpanded", 3, **extra) + stay_in_poi(3) + \
        return_to_trader(4, True)
    qid = f"npcquest_t{tier}_bandit_hideout"
    return qid, f"Tier {tier} Bandit Hideout", quest(qid, "bandit_hideout", tier, body, scaled_rewards("bandit_hideout", tier), True)


def rescue(tier):
    # No POIStayWithin: the survivors have to be led out of the POI
    body = go_to_poi(tier, False) + \
        objective("RescueDEM, QuestsExpanded", 3, survivors=RESCUE_SURVIVORS[tier]) + \
        return_to_trader(4, True)
    qid = f"npcquest_t{tier}_rescue"
    return qid, f"Tier {tier} Rescue", quest(qid, "rescue", tier, body, rescue_rewards(tier), True)


def safehouse(tier):
    body = [f'<action type="GameEvent" id="{SAFEHOUSE_KIT}" phase="1"/>'] + \
        objective("PlaceFlagDEM, QuestsExpanded", 1, block=SAFEHOUSE_FLAG, keyword="SafehouseDEM_flag_keyword") + \
        objective("SafehouseDEM, QuestsExpanded", 2, refugees=SAFEHOUSE_REFUGEES[tier], attack_hour=SAFEHOUSE_ATTACK_HOUR,
                  attack_waves=SAFEHOUSE_ATTACK_WAVES) + \
        return_to_trader(3, False)
    qid = f"npcquest_t{tier}_safehouse"
    return qid, f"Tier {tier} Safehouse", quest(qid, "safehouse", tier, body, scaled_rewards("safehouse", tier), False)


def all_quests():
    out = []
    for tier in TIERS:
        out.append(bandit_hideout(tier))
        out.append(rescue(tier))
        out.append(safehouse(tier))
    return out


def section(quests):
    out = [SECTION_START, "\t<insertAfter xpath=\"/quests/quest[@id='tier2_buried_supplies']\">"]
    for _, _, lines in quests:
        out += ["\t\t" + line if line else "" for line in lines]
        out.append("")
    out[-1] = "\t</insertAfter>"
    out += ["", "\t<append xpath=\"/quests/quest_list[starts-with(@id, 'trader_')]\">"]
    out += [f'\t\t<quest id="{qid}"/>' for qid, _, _ in quests]
    out += ["\t</append>", SECTION_END]
    return "\n".join(out)


def gameevents():
    return "\n".join([EVENTS_START, '\t<append xpath="/gameevents">'] +
                     defense.kit_event(SAFEHOUSE_KIT, [(SAFEHOUSE_FLAG, 1)]) +
                     ["\t</append>", EVENTS_END])


def localization_rows(quests):
    rows = [f"{key},UI,Quest,,,,{csv_field(text)},,,,,,,,,,,,," for key, text in OBJECTIVE_TEXT.items()]
    for kind, texts in QUEST_TEXT.items():
        for field, text in texts.items():
            if field == "title":
                continue
            category = ("Quest", "Quest Info") if field in ("statement", "response") else ("quests", "Quests")
            rows.append(f"npcquest_{kind}_{field},{category[0]},{category[1]},,,,{csv_field(text)},,,,,,,,,,,,,")
    for qid, title, _ in quests:
        rows.append(f"{qid}_name,quests,Quests,,,,{csv_field(title)},,,,,,,,,,,,,")
    return rows


def update_mod(mod_dir, quests):
    quests_path = os.path.join(mod_dir, "Config", "quests.xml")
    text = open(quests_path, encoding="utf-8", newline="").read().replace("\r\n", "\n")
    block = section(quests)
    if SECTION_START in text:
        text = re.sub(re.escape(SECTION_START) + ".*?" + re.escape(SECTION_END), lambda m: block, text, flags=re.S)
    else:
        end = text.rindex("</Dementive>")
        text = text[:end].rstrip("\n") + "\n\n" + block + "\n\n" + text[end:]
    open(quests_path, "w", encoding="utf-8", newline="").write(text.replace("\n", "\r\n"))

    defense.write_section(os.path.join(mod_dir, "Config", "gameevents.xml"), EVENTS_START, EVENTS_END, gameevents())

    loc_path = os.path.join(mod_dir, "Config", "Localization.csv")
    loc = open(loc_path, encoding="utf-8", newline="").read().replace("\r\n", "\n").rstrip("\n").split("\n")
    loc = [line for line in loc if not line.startswith(LOC_PREFIXES)] + localization_rows(quests)
    open(loc_path, "w", encoding="utf-8", newline="").write("\r\n".join(loc) + "\r\n")


if __name__ == "__main__":
    quests = all_quests()
    for mod in MODS:
        update_mod(mod, quests)
    print(f"{len(quests)} NPC quests written to {len(MODS)} mods")
