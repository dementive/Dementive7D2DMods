# Magazines offered as the fixed reward choice, by tier
MAGAZINE_COUNT = {1: 2, 2: 2, 3: 3, 4: 3, 5: 4, 6: 4}

SHARED_TEXT = {
    "commission_subtitle": "Craft the Order",
    "commission_statement": "Craft the order and bring it back.",
    "commission_completion": "That's exactly what I asked for. White River thanks you - here's your payment.",
}


def quest_id(order, tier):
    return f"commission_t{tier}_{order['id']}"


def reward_block(order, tier):
    """The mod's fetch rewards for the tier, with the order's magazine (and tool) as reward choices that are
    always offered."""
    base = [line.rstrip() for line in getattr(Rewards(), f"tier{tier}_fetch_rewards").strip("\n").split("\n")]
    while not base[-1]:
        base.pop()
    magazine = order["magazine"][tier] if isinstance(order["magazine"], dict) else order["magazine"]
    fixed = [f'\t<reward type="Item" id="{magazine}" value="{MAGAZINE_COUNT[tier]}" ischosen="true" isfixed="true"/>']
    tool = order.get("tools", {}).get(tier)
    if tool:
        fixed.append(f'\t<reward type="Item" id="{tool}" value="1" ischosen="true" isfixed="true"/>')
    # Insert the fixed choices after the Exp and casinoCoin rewards
    split = max(i for i, line in enumerate(base) if 'type="Exp"' in line or 'id="casinoCoin"' in line) + 1
    return base[:split] + fixed + base[split:]


def quest_xml(order, tier):
    qid = quest_id(order, tier)
    lines = [
        f'<quest id="{qid}">',
        f'\t<property name="name_key" value="{qid}_name"/>',
        '\t<property name="subtitle_key" value="commission_subtitle"/>',
        f'\t<property name="description_key" value="commission_{order["id"]}_description"/>',
        f'\t<property name="offer_key" value="commission_{order["id"]}_offer"/>',
        '\t<property name="statement_key" value="commission_statement"/>',
        f'\t<property name="response_key" value="commission_{order["id"]}_response"/>',
        '\t<property name="completion_key" value="commission_completion"/>',
        '\t<property name="icon" value="ui_game_symbol_hammer"/>',
        '\t<property name="category_key" value="quest"/>',
        f'\t<property name="difficulty_tier" value="{tier}"/>',
        '\t<property name="repeatable" value="true"/>',
        '\t<property name="shareable" value="true"/>',
        '\t<property name="unique_key" value="commission"/>',
        '\t<property name="reward_choices_count" value="5"/>',
        '\t<property name="completiontype" value="TurnIn"/>',
        "",
    ]
    for item, count in order["tiers"][tier]:
        assert 0 < count <= 255, (qid, item, count)
        lines.append(f'\t<objective type="Craft" item="{item}" count="{count}" phase="1"/>')
    lines.append("")
    for item, count in order["tiers"][tier]:
        lines.append(f'\t<objective type="DeliverDEM, QuestsExpanded" id="{item}" value="{count}" phase="2"/>')
    lines += [
        '\t<objective type="ReturnToNPC">',
        '\t\t<property name="phase" value="2"/>',
        '\t\t<property name="nav_object" value="return_to_trader"/>',
        "\t</objective>",
        '\t<objective type="InteractWithNPC">',
        '\t\t<property name="phase" value="2"/>',
        '\t\t<property name="nav_object" value="return_to_trader"/>',
        "\t</objective>",
        "",
    ]
    lines += reward_block(order, tier)
    lines.append("</quest>")
    return lines


def section():
    out = [SECTION_START, "\t<insertAfter xpath=\"/quests/quest[@id='tier2_buried_supplies']\">"]
    for order in ORDERS:
        for tier in sorted(order["tiers"]):
            out += ["\t\t" + line if line else "" for line in quest_xml(order, tier)]
            out.append("")
    out[-1] = "\t</insertAfter>"

    def quest_list(xpath, orders):
        ids = [quest_id(o, t) for o in orders for t in sorted(o["tiers"])]
        return ["", f'\t<append xpath="{xpath}">'] + [f'\t\t<quest id="{i}"/>' for i in ids] + ["\t</append>"]

    out += quest_list("/quests/quest_list[starts-with(@id, 'trader_')]", [o for o in ORDERS if o["trader"] is None])
    for trader in sorted({o["trader"] for o in ORDERS if o["trader"]}):
        out += quest_list(f"/quests/quest_list[@id='trader_{trader}_quests']", [o for o in ORDERS if o["trader"] == trader])
    out.append(SECTION_END)
    return "\n".join(out)


def csv_field(text):
    return '"' + text.replace('"', '""') + '"' if any(c in text for c in ',"') else text


def localization_rows():
    rows = []

    def row(key, text, file="quests", kind="Quests"):
        rows.append(f"{key},{file},{kind},,,,{csv_field(text)},,,,,,,,,,,,,")

    for key, text in SHARED_TEXT.items():
        row(key, text, *(("Quest", "Quest Info") if key == "commission_statement" else ("quests", "Quests")))
    for order in ORDERS:
        row(f"commission_{order['id']}_description", order["description"])
        row(f"commission_{order['id']}_offer", order["offer"])
        row(f"commission_{order['id']}_response", f"Commission: {order['title']}", "Quest", "Quest Info")
        for tier in sorted(order["tiers"]):
            row(f"{quest_id(order, tier)}_name", f"Tier {tier} Commission: {order['title']}")
    return rows


def update_mod(mod_dir):
    quests_path = os.path.join(mod_dir, "Config", "quests.xml")
    quests = open(quests_path, encoding="utf-8", newline="").read().replace("\r\n", "\n")
    block = section()
    if SECTION_START in quests:
        quests = re.sub(re.escape(SECTION_START) + ".*?" + re.escape(SECTION_END), lambda m: block, quests, flags=re.S)
    else:
        end = quests.rindex("</Dementive>")
        quests = quests[:end].rstrip("\n") + "\n\n" + block + "\n\n" + quests[end:]
    open(quests_path, "w", encoding="utf-8", newline="").write(quests.replace("\n", "\r\n"))

    loc_path = os.path.join(mod_dir, "Config", "Localization.csv")
    loc = open(loc_path, encoding="utf-8", newline="").read().replace("\r\n", "\n").rstrip("\n").split("\n")
    loc = [line for line in loc if not line.startswith("commission_")] + localization_rows()
    open(loc_path, "w", encoding="utf-8", newline="").write("\r\n".join(loc) + "\r\n")


